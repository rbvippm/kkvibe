def to_tw(src: str) -> str:
    if src in TW_OVERRIDE and TW_OVERRIDE[src]:
        return TW_OVERRIDE[src]
    cc = OpenCC("s2twp")
    out = cc.convert(src)
    out = (
        out.replace("賬號", "帳號")
        .replace("賬戶", "帳戶")
        .replace("賬單", "帳單")
        .replace("設定", "設置")
        .replace("使用者名稱", "用戶名")
        .replace("資訊與儲存", "數據與儲存")
        .replace("資料與儲存", "數據與儲存")
        .replace("占成", "佔成")
    )
    return out


def main():
    keys = json.loads(KEYS_PATH.read_text(encoding="utf-8"))
    seen = set()
    ordered = []
    for k in keys + EXTRA:
        if k not in seen:
            seen.add(k)
            ordered.append(k)

    missing = {lang: [] for lang in ("en", "th", "vi")}
    for k in ordered:
        if k not in EN:
            missing["en"].append(k)
        if k not in TH:
            missing["th"].append(k)
        if k not in VI:
            missing["vi"].append(k)
    if any(missing.values()):
        raise SystemExit(f"missing translations: {missing}")

    import re

    thai_re = re.compile(r"[\u0E00-\u0E7F]")
    vi_re = re.compile(
        r"[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđÀÁẢÃẠĂẰẮẲẴẶÂẦẤẨẪẬÈÉẺẼẸÊỀẾỂỄỆÌÍỈĨỊÒÓỎÕỌÔỒỐỔỖỘƠỜỚỞỠỢÙÚỦŨỤƯỪỨỬỮỰỲÝỶỸỴĐ]"
    )
    han_re = re.compile(r"[\u4e00-\u9fff]")
    simp_needles = ["账号", "占成", "记录", "设置", "详细", "默认", "登录"]

    en, th, vi, tw = {}, {}, {}, {}
    for k in ordered:
        en[k] = EN[k]
        th[k] = TH[k]
        vi[k] = VI[k]
        tw[k] = to_tw(k)

        if k != "金刚 KING KONG" and "金刚" in k and "King Kong" not in en[k] and "King Kong" not in th[k]:
            # 金刚 KING KONG maps to King Kong; others should mention King Kong
            pass
        if "金刚" in k and k not in ("金刚 KING KONG",):
            for loc, val in (("en", en[k]), ("th", th[k]), ("vi", vi[k])):
                if "King Kong" not in val:
                    raise SystemExit(f"{loc} missing King Kong for {k!r}: {val!r}")
            if "金剛" not in tw[k]:
                raise SystemExit(f"tw missing 金剛 for {k!r}: {tw[k]!r}")

        if not thai_re.search(th[k]) and th[k] not in ("King Kong", "VIP", "OK", "Hot", "Live", "Slot", "Me"):
            # allow short brand-like, but require Thai for product copy
            if len(th[k]) > 12 and not thai_re.search(th[k]):
                raise SystemExit(f"Thai missing script: {k!r} -> {th[k]!r}")

        if not vi_re.search(vi[k]) and vi[k] not in ("King Kong", "VIP", "OK", "Hot", "Live", "Slot", "Me", "Game"):
            if len(vi[k]) > 8 and not vi_re.search(vi[k]):
                raise SystemExit(f"Vietnamese missing diacritics: {k!r} -> {vi[k]!r}")

        if not han_re.search(tw[k]) and tw[k] not in ("King Kong",):
            if any("\u4e00" <= ch <= "\u9fff" for ch in k):
                raise SystemExit(f"TW missing Han: {k!r} -> {tw[k]!r}")
        for n in simp_needles:
            if n in tw[k]:
                raise SystemExit(f"TW still simplified {n!r} in {k!r}: {tw[k]!r}")

        for loc, val in (("en", en[k]), ("th", th[k]), ("vi", vi[k]), ("tw", tw[k])):
            if "{title}" in k and "{title}" not in val:
                raise SystemExit(f"{loc} dropped {{title}} for {k!r}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    files = {
        "en.json": en,
        "th.json": th,
        "vi.json": vi,
        "zh-TW.json": tw,
    }
    counts = {}
    for name, data in files.items():
        path = OUT_DIR / name
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        # roundtrip
        loaded = json.loads(path.read_text(encoding="utf-8"))
        assert list(loaded.keys()) == ordered
        assert all(isinstance(v, str) for v in loaded.values())
        counts[name] = len(loaded)
        print(f"{name}: {len(loaded)} keys")

    print("source keys.json:", len(keys))
    print("extra added:", len(ordered) - len(keys))
    print("total unique:", len(ordered))


if __name__ == "__main__":
    main()
